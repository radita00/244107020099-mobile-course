/// Entity murni untuk Catatan (Note).
/// Tidak ada import Flutter, tidak ada mapping toMap/fromMap.
class Note {
  const Note({
    this.id,
    required this.title,
    this.body = '',
    required this.updatedAt,
    this.dirty = false,
  });

  final int? id;
  final String title;
  final String body;
  final DateTime updatedAt;
  final bool dirty;
}
